// 的半死状态（这也是"要等好久才出骨骼"的另一个来源）。
// 离线回放（tools/replay_test.js）里没有 mp-loader.js，退回 CDN 常量即可——回放不取模型文件。
function mpBase(pkg, fallback) {
  try {
    if (typeof window !== 'undefined') {
      if (window.MP_RESOLVED && window.MP_RESOLVED[pkg]) return window.MP_RESOLVED[pkg];
      if (typeof window.mpBaseUrl === 'function') return window.mpBaseUrl(pkg, fallback);
    }
  } catch (ignored) {}
  return fallback;
}
