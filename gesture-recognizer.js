  /**
   * 双手合并特征：把两只手**已经 EMA 平滑过**的单手特征聚合成一组对称量。
   * 对称 = 交换 a/b 结果完全不变，所以不依赖 MediaPipe 给出的手序（手序会随遮挡来回跳）。
   *   pMinExt1/pMinExt2  两手食指/中指伸展度的**较小值**：要求"两只手都伸了食指+中指"
   *   pMaxMx3            两手中/无名/小指伸展度最大值的**较大值**
   *   pMaxHy / pMinNd    两手高度的**较大值**（更高的那只也要在肩下）、离鼻尖的**较小值**
   *   pDxProd            两手食指 x 分量的**乘积**：＜0 = 一只朝左一只朝右（指尖相对）；
   *                      ≤−0.35 还要求两边都"横得够明显"，避免一只手垂着时 dx1≈0 蒙对符号
   *   pTipGap/pPalmGap   两手**食指尖**间距 / 两手**掌心**间距（都用肩宽做单位）
   *   pGapR              = pTipGap ÷ pPalmGap：＜1 = 指尖比手掌更靠拢（"凑到一起"），
   *                      这是"指尖相对"除符号外的第二道证据，也顺带挡掉"两手并排挨在一起"
   *   pMinMn4            两手 `mn4` 的**较小值** = "两只手的四指都伸直"（011 高兴 的身份证维度，
   *                      009 认识 的无名指/小指是弯的，量不出来）
   *   pMaxMn4            两手 `mn4` 的**较大值**：与 pMinMn4 组合判"双手手形不对称"（012 爱 的身份证维度：
   *                      pMinMn4≤0.40 + pMaxMn4≥0.85 = 一只手握拳、一只手张开）
   *   pMaxSpr            两手 `spr` 的**较大值** = "两只手都并拢"（挡双手张开掌）
   *   pMaxNyp            两手 `nyp` 的**较大值**：≤ 负值 = "两只手掌心都朝上"（011 高兴）
   */
  staticPairFeatures(a, b) {
    if (!a || !b) return null;
    const tipGap = Math.hypot(a.txh - b.txh, a.tyh - b.tyh);
    const palmGap = Math.hypot(a.hx - b.hx, a.hy - b.hy);
    return {
      pMinExt0: Math.min(a.ext0, b.ext0),
      pMinExt1: Math.min(a.ext1, b.ext1),
      pMinExt2: Math.min(a.ext2, b.ext2),
      pMaxMx3: Math.max(a.mx3, b.mx3),
      pMaxHy: Math.max(a.hy, b.hy),
      pMinNd: Math.min(a.nd, b.nd),
      pDxProd: a.dx1 * b.dx1,
      pTipGap: tipGap,
      pPalmGap: palmGap,
      pGapR: palmGap > 1e-6 ? tipGap / palmGap : 9.9,
      pMinMn4: Math.min(a.mn4, b.mn4),
      pMaxMn4: Math.max(a.mn4, b.mn4),
      pMaxSpr: Math.max(a.spr, b.spr),
      pMaxNyp: Math.max(a.nyp, b.nyp),
      pMinAbsDx1: Math.min(Math.abs(a.dx1), Math.abs(b.dx1)),
      pMaxEyeH: Math.max(a.eyeH, b.eyeH)
    };
  }

